#!/usr/bin/env bash
# Consulta del valor vigente de una clave de convención: la definida por
# el instalador en convenciones.sh o, si falta, el valor por defecto del
# catálogo de PERSONALIZE.md embebido abajo.
# Contrato D033: stdout solo datos parseables, stderr diagnósticos,
# exit 0 éxito, exit 1 clave desconocida o sin valor,
# exit 2 invocación inválida.
set -euo pipefail

uso() {
  cat >&2 <<'EOF'
uso: convencion.sh <clave>
imprime por stdout el valor vigente de la clave de convención:
el de convenciones.sh si la define; si no, el valor por defecto
del catálogo. Clave desconocida o sin valor: exit 1.
EOF
  exit 2
}

[ $# -eq 1 ] || uso
pedida=$1
clave=$(printf '%s' "$pedida" | tr '[:lower:]' '[:upper:]')

conv="$(dirname "$0")/convenciones.sh"
if [ -f "$conv" ]; then
  . "$conv" 2>/dev/null || { echo "convencion.sh: convenciones malformadas: $conv" >&2; exit 2; }
fi

# Catálogo completo con los valores por defecto de PERSONALIZE.md:
# una clave ausente en convenciones.sh rige por estos valores.
INDICE_TAREAS=${INDICE_TAREAS:-TODO.md}
DIR_TAREAS=${DIR_TAREAS:-docs/tasks}
DIR_PROPUESTAS=${DIR_PROPUESTAS:-docs/proposals}
ARCHIVO_PROPUESTA=${ARCHIVO_PROPUESTA:-propuesta.md}
DIR_IDEAS=${DIR_IDEAS:-docs/ideas}
DIR_EPICAS=${DIR_EPICAS:-docs/epics}
DIR_DECISIONES=${DIR_DECISIONES:-docs/decisions}
DIR_LECCIONES=${DIR_LECCIONES:-docs/lessons}
DIR_DOMINIOS=${DIR_DOMINIOS:-docs/domains}
DIR_INVESTIGACIONES=${DIR_INVESTIGACIONES:-docs/research}
DIR_REVISIONES_ARQUITECTURA=${DIR_REVISIONES_ARQUITECTURA:-docs/architecture-reviews}
DIR_PRD=${DIR_PRD:-docs/prd}
DIR_DOCS_PRODUCTO=${DIR_DOCS_PRODUCTO:-product-docs}
ARCHIVO_EXPERIENCIAS=${ARCHIVO_EXPERIENCIAS:-EXPERIENCIAS.md}
ARCHIVO_CHANGELOG=${ARCHIVO_CHANGELOG:-CHANGELOG.md}
ARCHIVO_ROADMAP=${ARCHIVO_ROADMAP:-ROADMAP.md}
ARCHIVO_DESIGN=${ARCHIVO_DESIGN:-DESIGN.md}
MARCA_PENDIENTE=${MARCA_PENDIENTE:-" "}
MARCA_EN_PROGRESO="${MARCA_EN_PROGRESO:-"~"}"
MARCA_EN_REVISION=${MARCA_EN_REVISION:-r}
MARCA_COMPLETADA=${MARCA_COMPLETADA:-x}
MARCA_BLOQUEADA=${MARCA_BLOQUEADA:-"!"}
MARCA_PROPUESTA=${MARCA_PROPUESTA:-p}
MARCA_APROBADA=${MARCA_APROBADA:-a}
MARCA_DESCARTADA=${MARCA_DESCARTADA:-d}
ESTADO_PENDIENTE=${ESTADO_PENDIENTE:-Pendiente}
ESTADO_EN_PROGRESO=${ESTADO_EN_PROGRESO:-En progreso}
ESTADO_EN_REVISION=${ESTADO_EN_REVISION:-En revisión}
ESTADO_COMPLETADA=${ESTADO_COMPLETADA:-Completada}
ESTADO_BLOQUEADA=${ESTADO_BLOQUEADA:-Bloqueada}
ESTADO_BORRADOR=${ESTADO_BORRADOR:-Borrador}
ESTADO_PENDIENTE_REVISION=${ESTADO_PENDIENTE_REVISION:-Pendiente de revisión}
ESTADO_APROBADA=${ESTADO_APROBADA:-Aprobada}
ESTADO_DESCARTADA=${ESTADO_DESCARTADA:-Descartada}
ESTADO_PLANIFICADA=${ESTADO_PLANIFICADA:-Planificada}
SECCION_GENERAL=${SECCION_GENERAL:-General}
SECCION_PROPUESTAS=${SECCION_PROPUESTAS:-Propuestas en revisión}
SECCION_HITO=${SECCION_HITO:-Hito}
SECCION_ESTADO=${SECCION_ESTADO:-Estado}
SECCION_REVISION=${SECCION_REVISION:-Revisión}
SECCION_DEPENDENCIAS=${SECCION_DEPENDENCIAS:-Dependencias}
SECCION_DESVIACIONES=${SECCION_DESVIACIONES:-Desviaciones del plan}
SECCION_PLAN=${SECCION_PLAN:-Plan técnico}
SECCION_SUITE=${SECCION_SUITE:-Suite de pruebas esperada}
SECCION_CONTEXTO=${SECCION_CONTEXTO:-Contexto}
SECCION_CONECTIVIDAD=${SECCION_CONECTIVIDAD:-Conectividad}
SECCION_BORRADORES=${SECCION_BORRADORES:-Borradores}
SECCION_PIEZAS=${SECCION_PIEZAS:-Piezas}
ANCHO_NUMERACION=${ANCHO_NUMERACION:-3}
ANCHO_BORRADOR=${ANCHO_BORRADOR:-2}
PREFIJO_DECISION=${PREFIJO_DECISION:-D}
PREFIJO_CASO_USO=${PREFIJO_CASO_USO:-CU}
REF_BORRADOR=${REF_BORRADOR:-Borrador}
FORMATO_LINEA_TAREA=${FORMATO_LINEA_TAREA:-- [%s] %s — %s}
FORMATO_LINEA_PROPUESTA=${FORMATO_LINEA_PROPUESTA:-- [%s] %s/ — %s (%s borradores)}
FORMATO_BLOQUEANTE=${FORMATO_BLOQUEANTE:-  - [ ] %s}
COMENTARIO_EPICA=${COMENTARIO_EPICA:-épica}
FORMATO_VEREDICTO=${FORMATO_VEREDICTO:-- %s: %s — %s}
MARCADOR_FECHA=${MARCADOR_FECHA:-'[fecha]'}
OPCIONES_VEREDICTO=${OPCIONES_VEREDICTO:-Aprueba | Solicita cambios}
ACTORES_REVISION=${ACTORES_REVISION:-Subagente|Usuario (ejecución)|Usuario (cierre)}
REF_DEPENDE=${REF_DEPENDE:-depende de}
DEPENDENCIAS_VACIA=${DEPENDENCIAS_VACIA:-Ninguna}
CAMPO_PROCESADA=${CAMPO_PROCESADA:-> **Procesada en:** %s}
CAMPO_ORDEN_IDEA=${CAMPO_ORDEN_IDEA:-'**Orden sugerido:**'}
CAMPOS_EXPERIENCIA=${CAMPOS_EXPERIENCIA:-Id Tarea Esperado Obtenido Corrección}
CAMPO_ESTADO_EXPERIENCIA=${CAMPO_ESTADO_EXPERIENCIA:-Estado}
ESTADO_EXPERIENCIA_PENDIENTE=${ESTADO_EXPERIENCIA_PENDIENTE:-pendiente}
ESTADO_EXPERIENCIA_CONSOLIDADA=${ESTADO_EXPERIENCIA_CONSOLIDADA:-consolidada}
CAMPOS_INDICE_DISPARADORES=${CAMPOS_INDICE_DISPARADORES:-Disparadores|Resumen|Estado}
PREFIJO_RAMA_TAREA=${PREFIJO_RAMA_TAREA:-tarea/}
RAMA_PRINCIPAL=${RAMA_PRINCIPAL:-main}

case "$clave" in
  INDICE_TAREAS|DIR_TAREAS|DIR_PROPUESTAS|ARCHIVO_PROPUESTA|DIR_IDEAS|\
  DIR_EPICAS|DIR_DECISIONES|DIR_LECCIONES|DIR_DOMINIOS|DIR_INVESTIGACIONES|\
  DIR_REVISIONES_ARQUITECTURA|DIR_PRD|DIR_DOCS_PRODUCTO|ARCHIVO_EXPERIENCIAS|\
  ARCHIVO_CHANGELOG|ARCHIVO_ROADMAP|ARCHIVO_DESIGN|\
  MARCA_PENDIENTE|MARCA_EN_PROGRESO|MARCA_EN_REVISION|MARCA_COMPLETADA|\
  MARCA_BLOQUEADA|MARCA_PROPUESTA|MARCA_APROBADA|MARCA_DESCARTADA|\
  ESTADO_PENDIENTE|ESTADO_EN_PROGRESO|ESTADO_EN_REVISION|ESTADO_COMPLETADA|\
  ESTADO_BLOQUEADA|ESTADO_BORRADOR|ESTADO_PENDIENTE_REVISION|ESTADO_APROBADA|\
  ESTADO_DESCARTADA|ESTADO_PLANIFICADA|\
  SECCION_GENERAL|SECCION_PROPUESTAS|SECCION_HITO|SECCION_ESTADO|\
  SECCION_REVISION|SECCION_DEPENDENCIAS|SECCION_DESVIACIONES|SECCION_PLAN|\
  SECCION_SUITE|SECCION_CONTEXTO|SECCION_CONECTIVIDAD|SECCION_BORRADORES|\
  SECCION_PIEZAS|\
  ANCHO_NUMERACION|ANCHO_BORRADOR|PREFIJO_DECISION|PREFIJO_CASO_USO|\
  REF_BORRADOR|\
  FORMATO_LINEA_TAREA|FORMATO_LINEA_PROPUESTA|FORMATO_BLOQUEANTE|\
  COMENTARIO_EPICA|FORMATO_VEREDICTO|\
  MARCADOR_FECHA|OPCIONES_VEREDICTO|ACTORES_REVISION|REF_DEPENDE|\
  DEPENDENCIAS_VACIA|CAMPO_PROCESADA|CAMPO_ORDEN_IDEA|CAMPOS_EXPERIENCIA|\
  CAMPO_ESTADO_EXPERIENCIA|\
  ESTADO_EXPERIENCIA_PENDIENTE|ESTADO_EXPERIENCIA_CONSOLIDADA|\
  CAMPOS_INDICE_DISPARADORES|PREFIJO_RAMA_TAREA|RAMA_PRINCIPAL)
    ;;
  *)
    echo "convencion.sh: clave desconocida: $pedida" >&2; exit 1 ;;
esac

valor=${!clave:-}
[ -n "$valor" ] || { echo "convencion.sh: clave sin valor: $pedida" >&2; exit 1; }
printf '%s\n' "$valor"
